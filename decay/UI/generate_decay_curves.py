import numpy as np

xT = np.linspace(1,55,10)
tauF = 10.0
tauR = 20.0
frt = 0.75
testF = np.exp(-xT/tauF)
testR = (1-frt)*np.exp(-xT/tauR) + frt*tauR/(tauF-tauR)*(np.exp(-xT/tauF) -np.exp(-xT/tauR)) +frt*testF
for i,dis in enumerate(xT):
    print(f'{dis}   {testR[i]} ')
for i,dis in enumerate(xT):
    print(f'{dis}   {testF[i]} ')

